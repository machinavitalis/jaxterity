"""Reference robot zoo — arms, a humanoid, and a quadrotor.

Currently registered: **Cartpole**, **SO-100/SO-101**, the **Unitree G1**
(29-DoF humanoid), and the **Crazyflie 2.0** (nano-quadrotor).
The arms and the G1's default form are fixed-base (``nq == nv``); the G1 also
offers a floating-base topology (``load(floating_base=True)``) and the Crazyflie
is floating-base only (a free body — ``nq == 7``, ``nv == 6``), with a body
thrust+moment wrench model (``crazyflie.thrust_dynamics``). Follow-on work:
legged contact / locomotion for the G1, four-rotor control allocation and a
hover/trajectory controller for the Crazyflie (see ``AGENTS/LIBRARIES.md``).

Each entry is a subpackage exposing ``load() -> Robot`` (built from a vendored,
license-checked URDF/MJCF) plus a free-fall golden trajectory and a README. The
zoo is the regression ground truth (CONTEXT.md invariant 7): any change to a
core abstraction must keep every zoo robot importing, simulating, and matching
its golden.

Initial entries are uncalibrated (free-fall goldens); calibrated parameter sets
land later.
"""

from __future__ import annotations

import importlib.resources
import json

import jax.numpy as jnp

from ..errors import ZooError
from ..robot import Robot
from ..sysid.result import SysidResult
from . import cartpole, crazyflie, so100, unitree_g1

#: Registered zoo robots by name. New robots register here as their assets land.
ROBOTS = {
    "cartpole": cartpole,
    "so100": so100,
    "unitree_g1": unitree_g1,
    "crazyflie": crazyflie,
}


def available() -> list[str]:
    """Names of the registered zoo robots."""
    return sorted(ROBOTS)


def load(name: str) -> Robot:
    """Load a zoo robot by name.

    Args
    ----
    name : str
        One of :func:`available`.

    Returns
    -------
    Robot
        The (uncalibrated) reference robot.

    Raises
    ------
    ZooError
        If ``name`` is not a registered zoo robot.
    """
    if name not in ROBOTS:
        raise ZooError(f"Unknown zoo robot {name!r}. Available: {available()}.")
    return ROBOTS[name].load()


def calibrated(name: str) -> Robot:
    """Load a zoo robot with its committed calibrated parameters applied.

    Reads ``calibrated.json`` from the robot's package directory (if present)
    and returns a Robot with those parameters bound + the calibration
    provenance recorded on the attestation chain (ADR-008). If no
    ``calibrated.json`` exists, raises :class:`ZooError` directing the caller
    to either run the relevant sysid recipe and commit the result, or use the
    uncalibrated :func:`load`.

    The current calibrations are **synthetic** — produced by running
    the sysid recipes on telemetry generated by the URDF defaults — and so
    the fitted values equal the defaults (up to fitter noise). Real-hardware
    calibrations land as a follow-up; the file format and API
    are stable so that swap is a data change, not an API one.

    The committed JSON is::

        {
          "recipe_name":    "sysid.<recipe>",
          "recipe_version": "1.0",
          "telemetry_hash": "<hex>",
          "fitted":         {"<comp>.<field>": <float>, ...},
          "residuals":      {"<quantity>": <float>, ...},
          "synthetic":      true  // true for committed defaults; false for real fits
        }

    Raises
    ------
    ZooError
        If ``name`` is unknown, or if no ``calibrated.json`` is present.
    """
    if name not in ROBOTS:
        raise ZooError(f"Unknown zoo robot {name!r}. Available: {available()}.")
    pkg = f"jaxterity.zoo.{name}"
    try:
        text = importlib.resources.files(pkg).joinpath("calibrated.json").read_text()
    except (FileNotFoundError, ModuleNotFoundError) as e:
        raise ZooError(
            f"zoo.calibrated({name!r}): no calibrated.json in {pkg}. "
            "Either run the relevant sysid recipe and commit the result, or "
            f"use zoo.load({name!r}) for the uncalibrated robot."
        ) from e
    payload = json.loads(text)
    robot = load(name)
    fitted_jax = {k: jnp.asarray(float(v)) for k, v in payload["fitted"].items()}
    res = SysidResult(
        fitted=fitted_jax,
        residuals=payload.get("residuals"),
        telemetry_hash=payload.get("telemetry_hash", ""),
        recipe_name=payload["recipe_name"],
        recipe_version=payload["recipe_version"],
    )
    return res.apply_to(robot)


def _closed_loop_result(robot: Robot, captures):
    """Merge per-joint closed-loop active-sysid fits into one SysidResult.

    ``captures`` is one :class:`~jaxterity.calibrate.CommandedCapture` or a sequence
    of them (one per excited joint, from real commanded-excitation telemetry). Each
    is fit with :func:`~jaxterity.calibrate.identify_closed_loop`; the fitted
    friction/damping leaves are merged and the per-joint held-out reductions are
    recorded in the residuals. The combined telemetry hash chains the per-capture
    hashes so the provenance covers every joint's data.
    """
    import hashlib

    from ..calibrate import identify_closed_loop
    from ..sysid import SysidResult

    seq = list(captures) if isinstance(captures, (list, tuple)) else [captures]
    if not seq:
        raise ZooError("recalibrate(recipe='closed_loop'): no captures provided.")
    fitted: dict = {}
    covariance: dict = {}
    residuals: dict = {}
    hashes = []
    for cap in seq:
        res = identify_closed_loop(robot, cap)
        fitted.update(res.fitted)
        if res.covariance:
            covariance.update(res.covariance)
        res_residuals = res.residuals or {}
        residuals[f"{cap.joint}.held_out_reduction"] = res_residuals.get(
            "held_out_reduction", 0.0
        )
        # Surface how many channels were *held* (non-identifiable, left at the
        # prior) so the artifact records non-identifiability instead of silently
        # dropping a joint's params.
        residuals[f"{cap.joint}.n_held_channels"] = res_residuals.get(
            "n_held_channels", 0.0
        )
        hashes.append(res.telemetry_hash)
    combined = hashlib.blake2b(
        "".join(sorted(hashes)).encode(), digest_size=16
    ).hexdigest()
    return SysidResult(
        fitted=fitted,
        covariance=covariance or None,
        residuals=residuals,
        telemetry_hash=combined,
        recipe_name="active.closed_loop",
        recipe_version="1.0",
    )


def recalibrate(
    name: str,
    telemetry,
    *,
    recipe: str = "inertial",
    write: bool = True,
    note: str = "",
) -> tuple[Robot, dict]:
    """Recalibrate a zoo robot from real telemetry; optionally commit.

    The follow-up that makes the synthetic ``calibrated.json``
    artifacts replaceable by real-hardware fits. Loads the robot, runs the
    selected sysid recipe on the provided telemetry, builds the new
    ``calibrated.json`` payload, and (if ``write=True``) overwrites the
    committed file in place.

    Args
    ----
    name : str
        Zoo robot name.
    telemetry : JointTelemetry | CommandedCapture | Sequence[CommandedCapture]
        Real or high-fidelity-synthetic telemetry the recipe consumes. The
        ``inertial`` / ``full_body`` / ``contact`` recipes consume a
        :class:`~jaxterity.data.JointTelemetry`; ``closed_loop`` consumes one or
        more :class:`~jaxterity.calibrate.CommandedCapture` (one per excited joint).
    recipe : str
        One of ``"inertial"`` / ``"full_body"`` / ``"contact"`` (recipes for
        masses/inertias) or ``"closed_loop"`` (per-joint viscous/Coulomb
        friction from a commanded-excitation capture). Defaults to ``"inertial"``.
    write : bool
        Whether to overwrite the committed ``calibrated.json`` in the
        robot's package directory. Defaults to True. Set False for a
        dry-run that just returns the calibrated Robot and the payload dict.
    note : str
        Optional human-readable note written into the JSON ``"note"`` field.
        Useful for recording the hardware / date / experimenter context.

    Returns
    -------
    (Robot, dict)
        The newly calibrated Robot and the payload dict (matching the
        on-disk JSON shape; ``"synthetic": False`` because this came from a
        real fit, not the URDF defaults).

    Raises
    ------
    ZooError
        If ``name`` is unknown.
    """
    import importlib
    from pathlib import Path

    from .. import sysid

    if name not in ROBOTS:
        raise ZooError(f"Unknown zoo robot {name!r}. Available: {available()}.")
    robot = load(name)
    if recipe == "closed_loop":
        result = _closed_loop_result(robot, telemetry)
    else:
        recipes = {
            "inertial": sysid.inertial,
            "full_body": sysid.full_body,
            "contact": sysid.contact,
        }
        if recipe not in recipes:
            raise ZooError(
                f"recalibrate: unknown recipe {recipe!r}. "
                f"Expected one of {sorted(recipes)} or 'closed_loop'."
            )
        result = recipes[recipe](telemetry, robot)
    calibrated_robot = result.apply_to(robot)
    payload = {
        "recipe_name": result.recipe_name,
        "recipe_version": result.recipe_version,
        "telemetry_hash": result.telemetry_hash,
        "fitted": {k: float(v) for k, v in result.fitted.items()},
        "residuals": {k: float(v) for k, v in (result.residuals or {}).items()},
        "synthetic": False,
        "note": note
        or f"Recalibrated via {result.recipe_name} on user-supplied telemetry.",
    }
    if write:
        mod_file = importlib.import_module(f"jaxterity.zoo.{name}").__file__
        assert mod_file is not None, f"zoo.{name} subpackage has no __file__"
        pkg_dir = Path(mod_file).parent
        out = pkg_dir / "calibrated.json"
        out.write_text(json.dumps(payload, indent=2) + "\n")
    return calibrated_robot, payload


