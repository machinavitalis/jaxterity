"""``Robot.functional_dynamics`` — the fast jit/vmap MJX path.

The functional dynamics is the env primitive the nanojaxterity PPO demo trains
on (``policies.S4.step`` rebuilds the simulator each call and is ~10⁶× too slow
for RL). These tests pin two things: it reproduces the engine's physics
bit-exactly (same committed free-fall golden the zoo regression uses), and it
``jit``/``vmap``-composes.
"""

from __future__ import annotations

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from jaxterity import zoo

pytest.importorskip("mujoco")


def _rk4(f, state, tau, dt):
    k1 = f(state, tau)
    k2 = f(state + 0.5 * dt * k1, tau)
    k3 = f(state + 0.5 * dt * k2, tau)
    k4 = f(state + dt * k3, tau)
    return state + dt / 6.0 * (k1 + 2 * k2 + 2 * k3 + k4)


def test_functional_dynamics_matches_freefall_golden():
    """Free-fall (tau=0) reproduces the committed cartpole golden bit-exactly.

    The golden is generated by the engine's diagram + ``jaxonomy.simulate``
    (rk4, max step 0.01) from q0=[0, 0.1], t=1.0. The functional path uses the
    same rk4 at dt=0.01; matching to ~1e-12 proves it is the same physics, not
    a re-derivation that happens to look similar.
    """
    robot = zoo.calibrated("cartpole")
    f = robot.functional_dynamics()
    state = jnp.array([0.0, 0.1, 0.0, 0.0])  # [cart_x, pole_θ, ẋ, θ̇]
    tau = jnp.zeros(2)
    for _ in range(100):  # t = 1.0 at dt = 0.01
        state = _rk4(f, state, tau, 0.01)
    golden = np.load(zoo.ROBOTS["cartpole"].URDF_PATH.with_name("golden_freefall.npz"))[
        "final_state"
    ]
    np.testing.assert_allclose(np.asarray(state), golden, atol=1e-12, rtol=0)


def test_functional_dynamics_jit_and_vmap():
    """The dynamics jit-compiles and vmaps over a batch of independent states."""
    robot = zoo.calibrated("cartpole")
    f = robot.functional_dynamics()
    step = jax.jit(lambda s, u: _rk4(f, s, u, 0.02))
    vstep = jax.jit(jax.vmap(step))
    states = jnp.tile(jnp.array([0.0, 0.1, 0.0, 0.0]), (8, 1))
    taus = jnp.linspace(-1.0, 1.0, 8)[:, None] * jnp.array([1.0, 0.0])
    out = vstep(states, taus)
    assert out.shape == (8, 4)
    assert np.all(np.isfinite(np.asarray(out)))
    # Distinct cart forces must produce distinct cart accelerations.
    assert len(np.unique(np.round(np.asarray(out)[:, 2], 9))) == 8


def test_functional_dynamics_applies_force_to_actuated_joint():
    """A positive force on the cart (dof 0) accelerates the cart positively."""
    robot = zoo.calibrated("cartpole")
    f = robot.functional_dynamics()
    state = jnp.zeros(4)
    dstate_pos = f(state, jnp.array([5.0, 0.0]))
    dstate_neg = f(state, jnp.array([-5.0, 0.0]))
    assert float(dstate_pos[2]) > 0.0  # q̈_cart > 0 under +force
    assert float(dstate_neg[2]) < 0.0
